#!/usr/bin/env node
/* tools/bundle-ai-tutor.mjs — concatenates the ai-tutor modules into ONE file that the
 * Supabase dashboard editor accepts (it takes a single index.ts).
 *   node tools/bundle-ai-tutor.mjs            → dist/ai-tutor.single.ts
 * Local imports are dropped (their code is concatenated in dependency order). Each module
 * lives in its own scope, so names are only kept when they are unique across modules.
 * The script fails if two modules export the same name, instead of silently shadowing. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const FN = join(ROOT, 'supabase/functions');
const ORDER = [
  '_shared/cors.ts',
  'ai-tutor/lib/validate.ts',
  'ai-tutor/lib/prompts.ts',
  'ai-tutor/lib/parser.ts',
  'ai-tutor/lib/providers.ts',
  'ai-tutor/lib/handler.ts',
  'ai-tutor/index.ts',
];

const seen = new Map();
const parts = [];
for (const rel of ORDER) {
  let src = await readFile(join(FN, rel), 'utf8');
  // every top-level export name must be unique across the bundle
  for (const m of src.matchAll(/^export\s+(?:async\s+)?(?:function|const|class|interface|type|let)\s+([A-Za-z_]\w*)/gm)) {
    const name = m[1];
    if (seen.has(name) && seen.get(name) !== rel) throw new Error(`name clash: "${name}" in ${seen.get(name)} and ${rel}`);
    seen.set(name, rel);
  }
  // drop local imports (they are concatenated above) and keep the rest
  src = src.replace(/^import\s+[^;]*from\s+['"]\.\.?\/[^'"]+['"];?\s*$/gm, '')
           .replace(/^import\s+type\s+[^;]*from\s+['"]\.\.?\/[^'"]+['"];?\s*$/gm, '')
           .replace(/^export\s+/gm, '');
  parts.push(`// ───── ${rel} ─────\n${src.trim()}\n`);
}
// external imports must be hoisted to the top of the single file
const external = new Set();
const body = parts.join('\n').replace(/^import\s+[^;]*from\s+['"](https?:[^'"]+|npm:[^'"]+|node:[^'"]+)['"];?\s*$/gm, (m) => { external.add(m.trim()); return ''; });
const header = `// ai-tutor — single-file build generated by tools/bundle-ai-tutor.mjs. Do not edit; edit the modules and rebuild.\n${[...external].join('\n')}\n`;
const out = join(ROOT, 'dist/ai-tutor.single.ts');
await mkdir(dirname(out), { recursive: true });
await writeFile(out, header + '\n' + body, 'utf8');
console.log(`✓ wrote dist/ai-tutor.single.ts (${(header.length + body.length).toLocaleString()} chars, ${ORDER.length} modules, ${external.size} external import(s))`);
